/** 这个节气轮换的一组：节气专属的那联打头，后面是当季的（去掉重复的） */
export function coupletPool(term: string): Couplet[] {
  const own = COUPLETS[term];
  const pool = own ? [own] : [];
  for (const couplet of SEASON_COUPLETS[seasonOfTerm(term)]) {
    if (!pool.some((p) => p.first === couplet.first)) pool.push(couplet);
  }
  return pool;
}
